create table public.promociones (
  id bigint generated by default as identity not null,
  hotel_id bigint,
  catalogo_destino_id bigint,
  imagen_principal text not null,
  precio_promocional numeric(12,2),
  precio_anterior numeric(12,2),
  descuento_porcentaje numeric(5,2),
  moneda text not null default 'MXN'::text,
  vigencia_desde date not null,
  vigencia_hasta date not null,
  viaje_desde date not null,
  viaje_hasta date not null,
  publicada boolean not null default false,
  created_at timestamp with time zone not null default now(),
  constraint promociones_catalogo_destino_id_fkey FOREIGN KEY (catalogo_destino_id) references public.catalogo_destinos(id),
  constraint promociones_check CHECK (((hotel_id IS NOT NULL) OR (catalogo_destino_id IS NOT NULL))),
  constraint promociones_check1 CHECK (((vigencia_hasta >= vigencia_desde) AND (viaje_hasta >= viaje_desde))),
  constraint promociones_check2 CHECK (((precio_promocional IS NOT NULL) OR (descuento_porcentaje IS NOT NULL))),
  constraint promociones_check3 CHECK (((precio_anterior IS NULL) OR (precio_promocional IS NULL) OR (precio_anterior > precio_promocional))),
  constraint promociones_descuento_porcentaje_check CHECK (((descuento_porcentaje > (0)::numeric) AND (descuento_porcentaje <= (100)::numeric))),
  constraint promociones_hotel_id_fkey FOREIGN KEY (hotel_id) references public.hoteles(id),
  constraint promociones_moneda_check CHECK ((moneda ~ '^[A-Z]{3}$'::text)),
  constraint promociones_pkey PRIMARY KEY (id),
  constraint promociones_precio_anterior_check CHECK ((precio_anterior >= (0)::numeric)),
  constraint promociones_precio_promocional_check CHECK ((precio_promocional >= (0)::numeric))
);
CREATE INDEX promociones_vigencia_idx ON public.promociones USING btree (publicada, vigencia_desde, vigencia_hasta);

alter table public.promociones enable row level security;


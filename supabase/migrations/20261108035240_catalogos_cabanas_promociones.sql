set local lock_timeout = '5s';

create table public.cabanas (
  id bigint generated by default as identity not null,
  catalogo_destino_id bigint not null,
  zona text,
  imagen_principal text not null,
  precio_desde numeric(12,2) not null,
  moneda text not null default 'MXN'::text,
  precio_por text not null,
  precio_personas integer not null,
  adultos_max integer not null,
  ninos_max integer not null default 0,
  habitaciones integer not null,
  disponible_desde date,
  disponible_hasta date,
  referencia_mapa text,
  publicada boolean not null default false,
  created_at timestamp with time zone not null default now(),
  constraint cabanas_adultos_max_check CHECK ((adultos_max > 0)),
  constraint cabanas_catalogo_destino_id_fkey FOREIGN KEY (catalogo_destino_id) references public.catalogo_destinos(id),
  constraint cabanas_check CHECK (((disponible_hasta IS NULL) OR (disponible_desde IS NULL) OR (disponible_hasta >= disponible_desde))),
  constraint cabanas_habitaciones_check CHECK ((habitaciones > 0)),
  constraint cabanas_moneda_check CHECK ((moneda ~ '^[A-Z]{3}$'::text)),
  constraint cabanas_ninos_max_check CHECK ((ninos_max >= 0)),
  constraint cabanas_pkey PRIMARY KEY (id),
  constraint cabanas_precio_desde_check CHECK ((precio_desde >= (0)::numeric)),
  constraint cabanas_precio_personas_check CHECK ((precio_personas > 0)),
  constraint cabanas_precio_por_check CHECK ((precio_por = ANY (ARRAY['noche'::text, 'estancia'::text])))
);
CREATE INDEX cabanas_destino_idx ON public.cabanas USING btree (catalogo_destino_id);

alter table public.cabanas enable row level security;

revoke all on public.cabanas from public, anon, authenticated;
grant select on public.cabanas to anon;
grant select, insert, update, delete on public.cabanas to authenticated, service_role;

create policy cabanas_select on public.cabanas
  for select to anon, authenticated
  using (publicada);

create policy cabanas_write on public.cabanas
  for all to authenticated
  using ((select public.es_administrador_actual()))
  with check ((select public.es_administrador_actual()));


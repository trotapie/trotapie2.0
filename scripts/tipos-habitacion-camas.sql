-- Ejecutar en el SQL Editor de Supabase ANTES de desplegar el frontend.
-- Después: crear tipos de cama y asociarlos desde Tipos de habitación.
-- Los registros existentes conservan su nombre y descripción en español.
-- Guardarlos desde el catálogo genera las traducciones a los idiomas configurados.
begin;

create table if not exists public.tipos_cama (
  id bigint generated by default as identity primary key,
  nombre text not null check (length(trim(nombre)) > 0),
  descripcion text not null default '',
  activo boolean not null default true
);
create table if not exists public.tipos_habitacion_camas (
  tipo_habitacion_id bigint not null references public.tipos_habitacion(id) on delete cascade,
  tipo_cama_id bigint not null references public.tipos_cama(id) on delete restrict,
  primary key (tipo_habitacion_id, tipo_cama_id)
);
create index if not exists tipos_habitacion_camas_cama_idx on public.tipos_habitacion_camas(tipo_cama_id);
create table if not exists public.tipos_habitacion_traducciones (
  tipo_habitacion_id bigint not null references public.tipos_habitacion(id) on delete cascade,
  idioma_id bigint not null references public.idiomas(id),
  nombre text not null check (length(trim(nombre)) > 0),
  descripcion text not null default '',
  primary key (tipo_habitacion_id, idioma_id)
);
create table if not exists public.tipos_cama_traducciones (
  tipo_cama_id bigint not null references public.tipos_cama(id) on delete cascade,
  idioma_id bigint not null references public.idiomas(id),
  nombre text not null check (length(trim(nombre)) > 0),
  descripcion text not null default '',
  primary key (tipo_cama_id, idioma_id)
);
create index if not exists tipos_habitacion_traducciones_idioma_idx on public.tipos_habitacion_traducciones(idioma_id);
create index if not exists tipos_cama_traducciones_idioma_idx on public.tipos_cama_traducciones(idioma_id);

-- Misma restricción administrativa utilizada en crear-destinos-catalogo.sql.
do $$
declare tabla text;
begin
  foreach tabla in array array['tipos_cama','tipos_habitacion_camas','tipos_habitacion_traducciones','tipos_cama_traducciones'] loop
    execute format('alter table public.%I enable row level security', tabla);
    execute format('grant select, insert, update, delete on public.%I to authenticated', tabla);
    execute format('drop policy if exists catalogo_lectura on public.%I', tabla);
    execute format('create policy catalogo_lectura on public.%I for select to authenticated using (true)', tabla);
    execute format('drop policy if exists catalogo_admin on public.%I', tabla);
    execute format('create policy catalogo_admin on public.%I for all to authenticated using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = ''admin'')) with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = ''admin''))', tabla);
  end loop;
end;
$$;
grant usage, select on sequence public.tipos_cama_id_seq to authenticated;

insert into public.tipos_habitacion_traducciones(tipo_habitacion_id, idioma_id, nombre, descripcion)
select h.id, i.id, h.nombre_habitacion, coalesce(h.descripcion, '')
from public.tipos_habitacion h cross join public.idiomas i
where lower(i.codigo) = 'es' and length(trim(h.nombre_habitacion)) > 0
on conflict (tipo_habitacion_id, idioma_id) do nothing;

-- Lectura pública limitada a los datos necesarios para cotizar, con fallback español.
create or replace function public.obtener_tipos_habitacion_camas(p_idioma text default 'es')
returns jsonb language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', h.id,
    'nombre_habitacion', coalesce(t.nombre, h.nombre_habitacion),
    'capacidad_maxima', h.capacidad_maxima,
    'camas', (
      select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'nombre', coalesce(ct.nombre, c.nombre)) order by c.id), '[]'::jsonb)
      from public.tipos_habitacion_camas hc
      join public.tipos_cama c on c.id = hc.tipo_cama_id and c.activo
      left join public.tipos_cama_traducciones ct on ct.tipo_cama_id = c.id
        and ct.idioma_id = (select id from public.idiomas where lower(codigo) = lower(p_idioma) limit 1)
      where hc.tipo_habitacion_id = h.id
    )
  ) order by h.id), '[]'::jsonb)
  from public.tipos_habitacion h
  left join public.tipos_habitacion_traducciones t on t.tipo_habitacion_id = h.id
    and t.idioma_id = (select id from public.idiomas where lower(codigo) = lower(p_idioma) limit 1);
$$;
revoke all on function public.obtener_tipos_habitacion_camas(text) from public;
grant execute on function public.obtener_tipos_habitacion_camas(text) to anon, authenticated;

-- Registro, asociaciones y traducciones se guardan en una sola transacción.
-- SECURITY INVOKER conserva las políticas RLS de las tablas existentes.
create or replace function public.guardar_tipo_habitacion_o_cama(
  p_catalogo text, p_id bigint, p_nombre text, p_descripcion text,
  p_capacidad integer, p_activo boolean, p_cama_ids bigint[], p_traducciones jsonb
) returns jsonb language plpgsql security invoker set search_path = '' as $$
declare registro_id bigint;
begin
  if not exists(select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin') then
    raise exception 'Tu rol no permite editar estos catálogos.' using errcode = '42501';
  end if;
  if length(trim(coalesce(p_nombre, ''))) = 0 then raise exception 'El nombre es obligatorio.'; end if;
  if jsonb_array_length(coalesce(p_traducciones, '[]'::jsonb)) = 0 then raise exception 'Faltan las traducciones del catálogo.'; end if;
  if p_catalogo = 'tipos_habitacion' then
    if p_capacidad is null or p_capacidad < 1 then raise exception 'La capacidad debe ser mayor que cero.'; end if;
    if p_id is null then
      insert into public.tipos_habitacion(nombre_habitacion, capacidad_maxima, descripcion)
      values(trim(p_nombre), p_capacidad, p_descripcion) returning id into registro_id;
    else
      update public.tipos_habitacion set nombre_habitacion = trim(p_nombre), capacidad_maxima = p_capacidad, descripcion = p_descripcion
      where id = p_id returning id into registro_id;
      if registro_id is null then raise exception 'No se encontró la habitación o no tienes permiso para editarla.'; end if;
    end if;
    delete from public.tipos_habitacion_camas where tipo_habitacion_id = registro_id;
    insert into public.tipos_habitacion_camas(tipo_habitacion_id, tipo_cama_id)
    select registro_id, cama_id from (select distinct unnest(p_cama_ids) as cama_id) camas;
    insert into public.tipos_habitacion_traducciones(tipo_habitacion_id, idioma_id, nombre, descripcion)
    select registro_id, t.idioma_id, t.nombre, coalesce(t.descripcion, '')
    from jsonb_to_recordset(p_traducciones) as t(idioma_id bigint, nombre text, descripcion text)
    on conflict (tipo_habitacion_id, idioma_id) do update set nombre = excluded.nombre, descripcion = excluded.descripcion;
  elsif p_catalogo = 'tipos_cama' then
    if p_id is null then
      insert into public.tipos_cama(nombre, descripcion, activo)
      values(trim(p_nombre), coalesce(p_descripcion, ''), p_activo) returning id into registro_id;
    else
      update public.tipos_cama set nombre = trim(p_nombre), descripcion = coalesce(p_descripcion, ''), activo = p_activo
      where id = p_id returning id into registro_id;
      if registro_id is null then raise exception 'No se encontró el tipo de cama o no tienes permiso para editarlo.'; end if;
    end if;
    insert into public.tipos_cama_traducciones(tipo_cama_id, idioma_id, nombre, descripcion)
    select registro_id, t.idioma_id, t.nombre, coalesce(t.descripcion, '')
    from jsonb_to_recordset(p_traducciones) as t(idioma_id bigint, nombre text, descripcion text)
    on conflict (tipo_cama_id, idioma_id) do update set nombre = excluded.nombre, descripcion = excluded.descripcion;
  else
    raise exception 'Catálogo no válido.';
  end if;
  return jsonb_build_object('id', registro_id);
end;
$$;
revoke all on function public.guardar_tipo_habitacion_o_cama(text,bigint,text,text,integer,boolean,bigint[],jsonb) from public;
grant execute on function public.guardar_tipo_habitacion_o_cama(text,bigint,text,text,integer,boolean,bigint[],jsonb) to authenticated;

notify pgrst, 'reload schema';
commit;
